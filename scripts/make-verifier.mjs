/**
 * Regenerates src/lib/vaultConfig.js — the login verifier.
 *
 *   npm run set-password
 *
 * The verifier is a salt plus a short ciphertext. Unlocking works by deriving
 * a key from whatever password is typed and trying to decrypt that ciphertext:
 * AES-GCM is authenticated, so only the right password produces a successful
 * decrypt. The password itself is therefore never written to disk, never
 * committed, and cannot be read back out of the repo — the only way through it
 * is to guess, and each guess costs a full PBKDF2 derivation.
 *
 * Run this whenever you want to change the password. Nothing else needs
 * touching; commit the regenerated vaultConfig.js and redeploy.
 */

import { webcrypto as crypto } from 'node:crypto';
import { createInterface } from 'node:readline';
import { readFileSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const ITERATIONS = 600_000;
const SENTINEL = 'toms-tools:vault:v1:';
const OUT = resolve(dirname(fileURLToPath(import.meta.url)), '../src/lib/vaultConfig.js');

const toB64 = (bytes) => Buffer.from(bytes).toString('base64');

const interactive = process.stdin.isTTY === true;

/**
 * Interactive prompts hide the password as it is typed, so it never lands in
 * terminal scrollback. When stdin is piped (CI, scripted setup) readline's
 * echo handling gets in the way, so that path just consumes three lines.
 */
function makePrompter() {
  if (!interactive) {
    const lines = readFileSync(0, 'utf8').split(/\r?\n/);
    let i = 0;
    return { ask: async () => lines[i++] ?? '', done() {} };
  }

  const rl = createInterface({ input: process.stdin, output: process.stdout, terminal: true });

  return {
    ask: (question, { hidden = false } = {}) =>
      new Promise((resolvePrompt) => {
        if (hidden) {
          const write = process.stdout.write.bind(process.stdout);
          rl._writeToOutput = (chunk) => {
            if (chunk.startsWith(question)) write(question);
          };
        }
        rl.question(question, (answer) => {
          if (hidden) {
            // Drop the override so the prototype's normal echo comes back.
            delete rl._writeToOutput;
            process.stdout.write('\n');
          }
          resolvePrompt(answer);
        });
      }),
    done: () => rl.close(),
  };
}

const prompter = makePrompter();

async function main() {
  const email = (await prompter.ask('Email: ')).trim().toLowerCase();
  const password = await prompter.ask('Password (hidden): ', { hidden: true });
  const confirm = await prompter.ask('Confirm password: ', { hidden: true });
  prompter.done();

  if (!email) throw new Error('Email is required.');
  if (password.length < 12) throw new Error('Use at least 12 characters.');
  if (password !== confirm) throw new Error('Passwords do not match.');

  const salt = crypto.getRandomValues(new Uint8Array(16));
  const iv = crypto.getRandomValues(new Uint8Array(12));

  const material = await crypto.subtle.importKey('raw', Buffer.from(password, 'utf8'), 'PBKDF2', false, [
    'deriveKey',
  ]);
  const key = await crypto.subtle.deriveKey(
    { name: 'PBKDF2', salt, iterations: ITERATIONS, hash: 'SHA-256' },
    material,
    { name: 'AES-GCM', length: 256 },
    false,
    ['encrypt', 'decrypt'],
  );
  const ct = await crypto.subtle.encrypt(
    { name: 'AES-GCM', iv },
    key,
    Buffer.from(SENTINEL + email, 'utf8'),
  );

  const file = `/**
 * Login verifier — generated by \`npm run set-password\`. Do not edit by hand.
 *
 * This file is safe to commit: it holds a salt and a ciphertext, not the
 * password. See scripts/make-verifier.mjs for how it is used.
 */

export const ITERATIONS = ${ITERATIONS};
export const SENTINEL = '${SENTINEL}';
export const SALT = '${toB64(salt)}';
export const CHECK = { iv: '${toB64(iv)}', ct: '${toB64(new Uint8Array(ct))}' };
`;

  await writeFile(OUT, file, 'utf8');
  console.log('\nWrote src/lib/vaultConfig.js — commit it and redeploy.');
}

main().catch((err) => {
  prompter.done();
  console.error(`\n${err.message}`);
  process.exit(1);
});
